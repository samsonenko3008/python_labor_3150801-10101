# Задача 2: Параметры помещения
# Нужно рассчитать геометрические параметры помещения и стоимость покраски стен

# Ввод исходных данных (длина, ширина, высота в метрах)
length = 5.0
width = 4.0
height = 2.75

# Цена покраски за квадратный метр (руб)
price_per_sq_m = 125


# Расчеты площади пола, площади стен, объема помещения и стоимости покраски стен
# Площадь пола 
floor_area = length * width

# Площадь стен (периметр умноженный на высоту)
walls_area = 2 * height * (length + width)

# Объём помещения
volume = length * width * height

# Итоговая стоимость покраски стен
total_cost = walls_area * price_per_sq_m


# Вывод результатов с округлением до 2 знаков
print(" ПАРАМЕТРЫ ПОМЕЩЕНИЯ ")
print(f"Площадь пола: {round(floor_area, 2)} м2")
print(f"Площадь стен: {round(walls_area, 2)} м2")
print(f"Объём: {round(volume, 2)} м3")
print(f"Стоимость покраски стен: {round(total_cost, 2)} руб.")
